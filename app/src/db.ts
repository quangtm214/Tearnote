import { Directory, File, Paths } from 'expo-file-system';
import * as SQLite from 'expo-sqlite';
import { normalizeTags, type TagId } from './tags';

/**
 * On-device SQLite — the source of truth for Entries. Works with no network and no account.
 * The server only holds a copy (ADR 0004). Schema must match docs/db.md.
 */
const db = SQLite.openDatabaseSync('tearnote.db');

db.execSync(`pragma journal_mode = WAL; pragma foreign_keys = ON;`);

/**
 * Old installs keyed received_comforts by comfort_id only. When the device changes server identity
 * (log out, log in as someone else) the server can deliver a Comfort already clipped to another Entry;
 * `insert or ignore` then drops it: the quota is spent and nothing shows. Copy the old table to the
 * (entry_id, comfort_id) key.
 */
const legacyKey = db
  .getAllSync<{ name: string; pk: number }>(`pragma table_info(received_comforts)`)
  .some((c) => c.name === 'entry_id' && c.pk === 0);

db.withTransactionSync(() => {
  if (legacyKey) db.execSync(`alter table received_comforts rename to received_comforts_cu`);
  db.execSync(`
  create table if not exists entries (
    id           text primary key,
    occurred_at  integer not null,                                 -- epoch ms, lúc khóc
    duration_min integer check (duration_min is null or duration_min >= 0),
    intensity    integer not null check (intensity between 1 and 5),
    tags         text not null,                                    -- JSON array TagId
    reflection   text,
    synced_at    integer,                                          -- null = chưa sao lưu
    deleted_at   integer                                           -- xoá mềm, để sync xoá bên kia
  );
  create index if not exists entries_occurred_idx on entries (occurred_at desc);

  create table if not exists attachments (
    id       text primary key,
    entry_id text not null references entries(id) on delete cascade,
    kind     text not null check (kind in ('image', 'audio')),
    path     text not null,
    remote   text
  );

  create table if not exists settings (
    key   text primary key,
    value text not null
  );

  create table if not exists received_comforts (
    comfort_id  text not null,
    entry_id    text not null references entries(id) on delete cascade,
    body        text not null,
    translated  integer not null default 0,
    received_at integer not null,
    thanked     integer not null default 0,
    primary key (entry_id, comfort_id)
  );
  `);
  if (legacyKey) {
    db.execSync(`
      insert into received_comforts (comfort_id, entry_id, body, translated, received_at, thanked)
        select comfort_id, entry_id, body, translated, received_at, thanked from received_comforts_cu;
      drop table received_comforts_cu;
    `);
  }
});

export type Entry = {
  id: string;
  occurredAt: number;
  durationMin: number | null;
  intensity: number;
  tags: TagId[];
  reflection: string | null;
};

type EntryRow = {
  id: string;
  occurred_at: number;
  duration_min: number | null;
  intensity: number;
  tags: string;
  reflection: string | null;
};

const toEntry = (r: EntryRow): Entry => ({
  id: r.id,
  occurredAt: r.occurred_at,
  durationMin: r.duration_min,
  intensity: r.intensity,
  tags: JSON.parse(r.tags),
  reflection: r.reflection,
});

/**
 * UUID v4 generated by SQLite (randomblob uses SQLite's secure random source). Hermes has no
 * `crypto.randomUUID`, and the id must be a real uuid because the server reuses it on sync (docs/db.md).
 */
const UUID_V4 = `select lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4'
  || substr(lower(hex(randomblob(2))), 2) || '-' || substr('89ab', abs(random()) % 4 + 1, 1)
  || substr(lower(hex(randomblob(2))), 2) || '-' || lower(hex(randomblob(6))) as id`;

const newId = () => db.getFirstSync<{ id: string }>(UUID_V4)!.id;

/** Photo / recording of an Entry. `uri` is a file:// URI usable directly by Image and the audio player. */
export type Attachment = { kind: 'image' | 'audio'; uri: string };

/**
 * `attachments` come from the picker / recorder cache, which the OS can clear at any time, so copy them
 * to the document directory before writing the DB. A failed copy throws before any row is written.
 * `path` is stored relative: iOS changes the container path on every app update.
 */
export function insertEntry(e: Omit<Entry, 'id'>, attachments: Attachment[] = []): string {
  const id = newId();
  const dir = new Directory(Paths.document, 'attachments');
  if (attachments.length) dir.create({ idempotent: true });
  const copied = attachments.map((att) => {
    const source = new File(att.uri);
    const attachmentId = newId();
    const fileName = attachmentId + source.extension;
    source.copySync(new File(dir, fileName));
    return { attachmentId, kind: att.kind, path: `attachments/${fileName}` };
  });

  db.withTransactionSync(() => {
    db.runSync(
      `insert into entries (id, occurred_at, duration_min, intensity, tags, reflection)
       values (?, ?, ?, ?, ?, ?)`,
      id,
      e.occurredAt,
      e.durationMin,
      e.intensity,
      JSON.stringify(normalizeTags(e.tags)),
      e.reflection,
    );
    for (const a of copied) {
      db.runSync(
        `insert into attachments (id, entry_id, kind, path) values (?, ?, ?, ?)`,
        a.attachmentId,
        id,
        a.kind,
        a.path,
      );
    }
  });
  return id;
}

/** In insertion order — the first photo is the one shown on the Timeline card. */
export function listAttachments(entryId: string): Attachment[] {
  return db
    .getAllSync<{ kind: Attachment['kind']; path: string }>(
      `select kind, path from attachments where entry_id = ? order by rowid`,
      entryId,
    )
    .map((r) => ({ kind: r.kind, uri: new File(Paths.document, r.path).uri }));
}

export function listEntries(): Entry[] {
  return db
    .getAllSync<EntryRow>(
      `select id, occurred_at, duration_min, intensity, tags, reflection
       from entries where deleted_at is null order by occurred_at desc`,
    )
    .map(toEntry);
}

export function getEntry(id: string): Entry | null {
  const r = db.getFirstSync<EntryRow>(
    `select id, occurred_at, duration_min, intensity, tags, reflection
     from entries where id = ? and deleted_at is null`,
    id,
  );
  return r ? toEntry(r) : null;
}

/**
 * Hard delete while there is no sync: the Entry row (attachments and received_comforts cascade — needs
 * foreign_keys = ON), then its files in attachments/. Leaving the files would make "delete" a lie.
 * With sync, a synced Entry keeps a `deleted_at` tombstone instead (docs/db.md).
 */
export function deleteEntry(id: string): void {
  const rows = db.getAllSync<{ path: string }>(`select path from attachments where entry_id = ?`, id);
  db.runSync(`delete from entries where id = ?`, id);
  for (const { path } of rows) {
    try {
      new File(Paths.document, path).delete();
    } catch {
      // File already gone is fine — the row is deleted.
    }
  }
}

export type ReceivedComfort = {
  comfortId: string;
  entryId: string;
  body: string;
  translated: boolean;
  thanked: boolean;
};

/** entry_id exists only here — the server must not know which Comfort belongs to which Entry (ADR 0004). */
export function saveReceivedComfort(c: Omit<ReceivedComfort, 'thanked'>): void {
  db.runSync(
    `insert or ignore into received_comforts
       (comfort_id, entry_id, body, translated, received_at)
     values (?, ?, ?, ?, ?)`,
    c.comfortId,
    c.entryId,
    c.body,
    c.translated ? 1 : 0,
    Date.now(),
  );
}

export function listReceivedComforts(entryId: string): ReceivedComfort[] {
  return db
    .getAllSync<{
      comfort_id: string;
      entry_id: string;
      body: string;
      translated: number;
      thanked: number;
    }>(
      `select comfort_id, entry_id, body, translated, thanked
       from received_comforts where entry_id = ? order by received_at desc`,
      entryId,
    )
    .map((r) => ({
      comfortId: r.comfort_id,
      entryId: r.entry_id,
      body: r.body,
      translated: r.translated === 1,
      thanked: r.thanked === 1,
    }));
}

// Match (entry_id, comfort_id): one Comfort can reach two Entries; thank only the one being viewed.
export function markThanked(entryId: string, comfortId: string): void {
  db.runSync(`update received_comforts set thanked = 1 where entry_id = ? and comfort_id = ?`, entryId, comfortId);
}

/**
 * User settings as key–value pairs. Device only, never synced.
 * Defaults live at the call site, not here.
 */
export function getSetting(key: string): string | null {
  return db.getFirstSync<{ value: string }>(`select value from settings where key = ?`, key)?.value
    ?? null;
}

export function setSetting(key: string, value: string): void {
  db.runSync(
    `insert into settings (key, value) values (?, ?)
     on conflict (key) do update set value = excluded.value`,
    key,
    value,
  );
}

/**
 * Switch that fully turns off receiving Comforts — one of the two safety nets in overview.md §6,
 * because the system cannot detect a crisis. Default ON: the pool is why Tearnote exists.
 * When off, no request button appears anywhere.
 */
export const isComfortReceivingEnabled = () => getSetting('nhan_comfort') !== 'tat';
export const setComfortReceivingEnabled = (enabled: boolean) => setSetting('nhan_comfort', enabled ? 'bat' : 'tat');
